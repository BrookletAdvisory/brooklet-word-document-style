# 4. Minimal end-to-end usage example
# -----------------------------------------------------------------------------

if __name__ == "__main__":
    doc = Document()
    ids = install_brooklet_numbering(doc)

    # --- Parties block (restarts at 1) -----------------------------------
    parties_id = new_parties_numid(doc)
    add_party(doc, parties_id, [
        ("Brooklet Advisory Limited", {"bold": True}),
        (", a company incorporated in Hong Kong ...", {}),
    ])
    add_party(doc, parties_id, [
        ("[COUNTERPARTY NAME]", {"bold": True}),
        (", a company incorporated in [...] ...", {}),
    ])

    # --- Background block (restarts at A) --------------------------------
    bg_id = new_background_numid(doc)
    add_background(doc, bg_id, "First recital ...")
    add_background(doc, bg_id, "Second recital ...")
    add_background(doc, bg_id, "Third recital ...")

    # --- Operative clauses (continuous 1., 2., 3., ... at Lvl 0) ---------
    add_clause_heading(doc, "Interpretation")
    add_subclause(doc, "The following definitions apply ...")
    add_subclause(doc, "Headings shall not affect interpretation ...")

    add_clause_heading(doc, "Term and Termination")
    add_subclause(doc, "This Agreement commences on ...")
    add_subclause(doc, "Either Party may terminate by giving notice if:")
    add_limb(doc, "the other commits a material breach;")
    add_limb(doc, "the other becomes insolvent; or")
    add_limb(doc, "regulatory action is taken against the other.")

    # --- Schedule No. column (restarts at 1) -----------------------------
    sch_id = new_schedule_numid(doc)
    table = doc.add_table(rows=4, cols=2)
    table.style = "Table Grid"
    table.rows[0].cells[0].text = "No."
    table.rows[0].cells[1].text = "Detail"
    for i in range(1, 4):
        add_schedule_row_no(table.rows[i].cells[0], sch_id)

    doc.save("brooklet_autonumbering_example.docx")
